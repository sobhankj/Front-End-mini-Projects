/**
 * Pick a random passage and optionally trim/expand to a word count.
 */
export function getPassage({ language = "en", difficulty = "medium", wordCount = null } = {}) {
  const lang = TEXTS[language] ? language : "en";
  const level = TEXTS[lang][difficulty] ? difficulty : "medium";
  const pool = TEXTS[lang][level];

  if (!wordCount || wordCount <= 0) {
    return pool[Math.floor(Math.random() * pool.length)];
  }

  const words = [];
  let guard = 0;
  while (words.length < wordCount && guard < 40) {
    const piece = pool[Math.floor(Math.random() * pool.length)].trim().split(/\s+/);
    words.push(...piece);
    guard += 1;
  }

  return words.slice(0, wordCount).join(" ");
}
